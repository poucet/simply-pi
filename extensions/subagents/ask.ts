/**
 * The child→parent question channel.
 *
 * A subagent that has hit a genuine fork in the road should be able to ask
 * rather than guess. The hard part is that the parent must learn of the question
 * *while the child's tool call is still running*: a tool result only reaches the
 * parent at `tool_execution_end`, so a child that returned its question and
 * waited for a follow-up would have already ended its turn — losing the very
 * context the question is about.
 *
 * So `ask_parent` announces through `onUpdate` (which pi forwards as
 * `tool_execution_update`, with `partialResult` intact) and then blocks inside
 * the tool, polling for an answer file. When the answer lands the tool returns
 * it as its result and the child carries on in the same turn, mid-thought.
 *
 * The file is the whole protocol, and it is deliberately dumb: two processes,
 * one directory, atomic rename. Nothing here needs the RPC channel, which means
 * an answer still arrives if the parent reloaded and revived the child in
 * between.
 *
 * By decision there is **no timeout** — a child waits until it is answered. That
 * makes visibility non-negotiable: see `waiting` in types.ts and the distinct
 * icon in the strip.
 */

import { join } from "node:path";

/** Where a child's answers live, inside its own session directory. */
export function answersDirectory(sessionDir: string): string {
	return join(sessionDir, "answers");
}

/**
 * Path of the answer to one question.
 *
 * The id is generated by the child and echoed by the parent; it is sanitized on
 * both sides because it ends up in a filename.
 */
export function answerPath(answersDir: string, questionId: string): string {
	return join(answersDir, `${sanitizeQuestionId(questionId)}.json`);
}

/**
 * Keep a question id to something that cannot escape its directory.
 *
 * The id crosses a process boundary as part of a path, so `../` or a slash in it
 * would let one side write outside the answers directory.
 */
export function sanitizeQuestionId(questionId: string): string {
	const cleaned = String(questionId).replace(/[^A-Za-z0-9_-]/g, "").slice(0, 64);
	return cleaned || "question";
}

/** What the parent writes, and the child reads back. */
export interface AnswerFile {
	questionId: string;
	answer: string;
	answeredAt: number;
	/** Who answered: the orchestrator itself, or the human through `/agents`. */
	answeredBy?: string;
}

export function parseAnswer(raw: string): AnswerFile | undefined {
	let value: any;
	try {
		value = JSON.parse(raw);
	} catch {
		return undefined; // A half-written file; the poller simply tries again.
	}
	if (!value || typeof value !== "object") return undefined;
	if (typeof value.answer !== "string") return undefined;
	return {
		questionId: String(value.questionId ?? ""),
		answer: value.answer,
		answeredAt: typeof value.answeredAt === "number" ? value.answeredAt : Date.now(),
		...(typeof value.answeredBy === "string" ? { answeredBy: value.answeredBy } : {}),
	};
}

/** A question a child is currently blocked on. */
export interface PendingQuestion {
	id: string;
	question: string;
	context?: string;
	askedAt: number;
}

/**
 * Read a question out of a `tool_execution_update` event.
 *
 * Returns `undefined` for anything that is not a well-formed `ask_parent`
 * announcement, so a malformed or hostile update cannot put an agent into a
 * waiting state it will never leave.
 */
export function questionFromUpdate(event: any, now = Date.now()): PendingQuestion | undefined {
	if (event?.toolName !== "ask_parent") return undefined;
	const details = event?.partialResult?.details ?? event?.details;
	if (!details || typeof details !== "object") return undefined;
	const id = typeof details.questionId === "string" ? details.questionId.trim() : "";
	const question = typeof details.question === "string" ? details.question.trim() : "";
	if (!id || !question) return undefined;
	return {
		id,
		question,
		...(typeof details.context === "string" && details.context.trim()
			? { context: details.context.trim() }
			: {}),
		askedAt: now,
	};
}
